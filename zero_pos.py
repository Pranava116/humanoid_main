#!/usr/bin/env python3
"""
PCA9685 — 16-Servo Zero Position (17-DOF Humanoid)
====================================================
Raspberry Pi 4B | PCA9685 over software I2C
  SDA = GPIO23 (physical pin 16)
  SCL = GPIO24 (physical pin 18)

Requires in /boot/firmware/config.txt (then reboot):
  dtoverlay=i2c-gpio,bus=3,i2c_gpio_sda=23,i2c_gpio_scl=24

Loads offsets from offsets.json (generated by calibrate.py).
When you command 0° to any motor, it adds that motor's offset
so the robot stands in its true zero/stand position.

Usage:
  python3 zero_pos.py                   # sweep all motors
  python3 zero_pos.py --mode center     # stand position and hold
  python3 zero_pos.py --mode sweep      # sweep all motors
  python3 zero_pos.py --mode wave       # wave test
  python3 zero_pos.py --mode interactive
  python3 zero_pos.py --channel 6       # test one motor
"""

import argparse
import time
import sys
import json
import os

# ─────────────────────────────────────────────────────────────────────────────
#  CONFIG
# ─────────────────────────────────────────────────────────────────────────────

PCA_I2C_ADDRESS = 0x40
PWM_FREQUENCY   = 50
OFFSETS_FILE    = "offsets.json"

# Software I2C bus created by the i2c-gpio overlay (GPIO23 = SDA, GPIO24 = SCL)
I2C_BUS = 3

MOTOR_MAP = {
    0:  "Motor 0  — head/neck",
    1:  "Motor 1  — left shoulder",
    2:  "Motor 2  — right waist",
    3:  "Motor 3  — right shoulder",
    4:  "Motor 4  — left arm",
    5:  "Motor 5  — left waist",
    6:  "Motor 6  — right hip",
    7:  "Motor 7  — right upper leg",
    8:  "Motor 8  — right knee",
    9:  "Motor 9  — right ankle",
    10: "Motor 10 — right foot (horizontal)",
    11: "Motor 11 — left hip",
    12: "Motor 12 — left upper leg",
    13: "Motor 13 — left knee",
    14: "Motor 14 — left ankle",
    15: "Motor 15 — left foot (horizontal)",
}

MOTOR_LIMITS = {ch: (500, 1500, 2500) for ch in range(16)}


# ─────────────────────────────────────────────────────────────────────────────
#  LOAD OFFSETS
# ─────────────────────────────────────────────────────────────────────────────

def load_offsets(filepath: str) -> dict:
    if os.path.exists(filepath):
        with open(filepath, "r") as f:
            raw = json.load(f)
        offsets = {int(k): float(v) for k, v in raw.items()}
        non_zero = {k: v for k, v in offsets.items() if v != 0}
        print(f"Loaded offsets from {filepath}")
        if non_zero:
            for ch, off in sorted(non_zero.items()):
                print(f"  Motor {ch:2d}  {MOTOR_MAP.get(ch,''):30}  {off:+.1f}°")
        else:
            print("  No offsets set — all motors at electrical zero.")
        print()
        return offsets
    else:
        print(f"No offsets file found ({filepath}).")
        print("Run calibrate.py first to set motor offsets.\n")
        return {}


# ─────────────────────────────────────────────────────────────────────────────
#  PCA9685 CONTROLLER
# ─────────────────────────────────────────────────────────────────────────────

class PCA9685Controller:
    def __init__(self, address=PCA_I2C_ADDRESS, freq=PWM_FREQUENCY,
                 offsets=None, bus=I2C_BUS):
        try:
            from adafruit_servokit import ServoKit
            from adafruit_extended_bus import ExtendedI2C
        except ImportError:
            sys.exit("Run: pip install adafruit-circuitpython-servokit adafruit-extended-bus")

        try:
            i2c = ExtendedI2C(bus)   # software I2C: SDA=GPIO23 (pin 16), SCL=GPIO24 (pin 18)
        except Exception as e:
            sys.exit(
                f"Could not open I2C bus {bus}: {e}\n"
                "Did you add this to config.txt and reboot?\n"
                "  dtoverlay=i2c-gpio,bus=3,i2c_gpio_sda=23,i2c_gpio_scl=24"
            )

        try:
            self.kit = ServoKit(channels=16, i2c=i2c, address=address, frequency=freq)
        except ValueError as e:
            sys.exit(
                f"{e}\n"
                f"Nothing answered on I2C bus {bus}. Check wiring and run:\n"
                f"  sudo i2cdetect -y {bus}"
            )

        self.offsets = offsets or {}

        for ch, (mn, ctr, mx) in MOTOR_LIMITS.items():
            self.kit.servo[ch].set_pulse_width_range(mn, mx)

        print(f"PCA9685 ready at address 0x{address:02X}, {freq} Hz, I2C bus {bus}")
        print(f"Managing {len(MOTOR_MAP)} motors.\n")

    def set_angle(self, channel: int, angle: float):
        """
        Move motor to angle (-90 to +90).
        Offset from offsets.json is added automatically.
        """
        offset    = self.offsets.get(channel, 0.0)
        raw_angle = max(-90.0, min(90.0, angle + offset))
        self.kit.servo[channel].angle = raw_angle + 90.0

    def center(self, channel: int):
        """Move motor to its calibrated zero (stand position)."""
        self.set_angle(channel, 0)

    def center_all(self):
        for ch in MOTOR_MAP:
            self.set_angle(ch, 0)
        time.sleep(0.8)

    def release(self, channel: int):
        self.kit.servo[channel].angle = None

    def release_all(self):
        for ch in MOTOR_MAP:
            self.release(ch)


# ─────────────────────────────────────────────────────────────────────────────
#  MODES
# ─────────────────────────────────────────────────────────────────────────────

def mode_center(ctrl: PCA9685Controller):
    print("Moving all motors to STAND position (0° + offsets)...")
    for ch, name in MOTOR_MAP.items():
        ctrl.center(ch)
        offset = ctrl.offsets.get(ch, 0.0)
        offset_str = f"  offset {offset:+.1f}°" if offset else ""
        print(f"  Ch {ch:2d}  {name}{offset_str}")
        time.sleep(0.05)
    print("\nRobot at stand position. Ctrl+C to release.")
    try:
        while True:
            time.sleep(1)
    except KeyboardInterrupt:
        pass


def mode_sweep(ctrl: PCA9685Controller, channels=None):
    targets = channels if channels is not None else list(MOTOR_MAP.keys())
    print(f"Sweeping {len(targets)} motor(s)...\n")

    for ch in targets:
        name   = MOTOR_MAP.get(ch, f"Channel {ch}")
        offset = ctrl.offsets.get(ch, 0.0)
        offset_str = f" [offset {offset:+.1f}°]" if offset else ""
        print(f"  Ch {ch:2d}  {name}{offset_str}")

        ctrl.center(ch)
        time.sleep(0.4)
        ctrl.set_angle(ch,  45)
        time.sleep(0.5)
        ctrl.set_angle(ch, -45)
        time.sleep(0.5)
        ctrl.center(ch)
        time.sleep(0.4)

    print("\nSweep complete.")


def mode_wave(ctrl: PCA9685Controller):
    print("Wave mode — 3 cycles\n")
    ctrl.center_all()
    time.sleep(0.5)

    for _ in range(3):
        for ch in range(16):
            ctrl.set_angle(ch, 40)
            time.sleep(0.08)
            ctrl.set_angle(ch, 0)
        for ch in range(15, -1, -1):
            ctrl.set_angle(ch, -40)
            time.sleep(0.08)
            ctrl.set_angle(ch, 0)

    print("Wave complete.")


def mode_interactive(ctrl: PCA9685Controller):
    print("\nInteractive mode")
    print("  '<ch> <angle>'   e.g. '6 45'   → motor 6 to 45°")
    print("  'all <angle>'    e.g. 'all 0'  → all motors to angle")
    print("  'sweep <ch>'     e.g. 'sweep 6'")
    print("  'stand'          → move all to stand position")
    print("  'list'           → show motors and offsets")
    print("  'q'              → quit\n")

    while True:
        try:
            raw = input("cmd > ").strip().lower()
            if not raw:
                continue

            if raw in ("q", "quit"):
                break

            elif raw == "list":
                for ch, name in MOTOR_MAP.items():
                    offset = ctrl.offsets.get(ch, 0.0)
                    offset_str = f"  offset {offset:+.1f}°" if offset else ""
                    print(f"  {ch:2d}  {name}{offset_str}")

            elif raw == "stand":
                ctrl.center_all()
                print("  All motors → stand position")

            elif raw.startswith("all "):
                angle = float(raw[4:])
                for ch in MOTOR_MAP:
                    ctrl.set_angle(ch, angle)
                print(f"  All motors → {angle:+.1f}°")

            elif raw.startswith("sweep "):
                ch = int(raw[6:])
                mode_sweep(ctrl, channels=[ch])

            else:
                parts = raw.split()
                ch    = int(parts[0])
                angle = float(parts[1])
                if ch not in MOTOR_MAP:
                    print(f"  Invalid channel. Use 0-15.")
                    continue
                ctrl.set_angle(ch, angle)
                offset    = ctrl.offsets.get(ch, 0.0)
                raw_angle = min(90, max(-90, angle + offset))
                print(f"  Ch {ch:2d} ({MOTOR_MAP[ch]}) → {angle:+.1f}° (raw {raw_angle:+.1f}°)")

        except (ValueError, IndexError):
            print("  Usage: '<channel 0-15> <angle -90 to 90>'")
        except KeyboardInterrupt:
            break


# ─────────────────────────────────────────────────────────────────────────────
#  MAIN
# ─────────────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(
        description="17-DOF Humanoid zero position — RPi 4B + PCA9685"
    )
    parser.add_argument("--mode",    choices=["center","sweep","wave","interactive"],
                        default="sweep")
    parser.add_argument("--channel", type=int, default=None)
    parser.add_argument("--address", type=lambda x: int(x,0), default=PCA_I2C_ADDRESS)
    parser.add_argument("--bus",     type=int, default=I2C_BUS,
                        help=f"I2C bus number (default: {I2C_BUS})")
    parser.add_argument("--file",    type=str, default=OFFSETS_FILE,
                        help="Offsets JSON file (default: offsets.json)")
    args = parser.parse_args()

    print("=" * 54)
    print("  17-DOF Humanoid Zero Position — RPi 4B")
    print("=" * 54 + "\n")

    offsets = load_offsets(args.file)
    ctrl    = PCA9685Controller(address=args.address, offsets=offsets, bus=args.bus)

    try:
        if args.mode == "center":
            mode_center(ctrl)
        elif args.mode == "sweep":
            channels = [args.channel] if args.channel is not None else None
            mode_sweep(ctrl, channels=channels)
        elif args.mode == "wave":
            mode_wave(ctrl)
        elif args.mode == "interactive":
            mode_interactive(ctrl)


    except KeyboardInterrupt:
        print("\nInterrupted.")
    finally:
        print("Releasing all servos...")
        ctrl.release_all()
        print("Done.")


if __name__ == "__main__":
    main()
